-- Раздельные отметки для полного и быстрого прохода.
--
-- `last_synced_at` держит любой проход и им же гасится кулдаун. Быстрый проход
-- (только новое) стоит Telegram на порядок дешевле полного, поэтому пускать его
-- можно чаще — но пока отметка была одна, быстрый проход закрывал дорогу
-- полному на те же полчаса.
ALTER TABLE channels ADD COLUMN last_full_synced_at DATETIME;

-- До этой версии любой проход был полным.
UPDATE channels SET last_full_synced_at = last_synced_at;
