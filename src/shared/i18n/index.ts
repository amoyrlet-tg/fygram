import { useCallback, useSyncExternalStore } from "react";

export type Lang = "ru" | "en" | "uk" | "be" | "kk";

export const LANGUAGES: { code: Lang; country: string; native: string }[] = [
  { code: "ru", country: "ru", native: "Русский" },
  { code: "en", country: "gb", native: "English" },
  { code: "uk", country: "ua", native: "Українська" },
  { code: "be", country: "by", native: "Беларуская" },
  { code: "kk", country: "kz", native: "Қазақша" },
];

let lang: Lang = (localStorage.getItem("lang") as Lang | null) ?? "ru";
const listeners = new Set<() => void>();

function subscribe(listener: () => void) {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

function currentLang(): Lang {
  return lang;
}

export function setLang(next: Lang) {
  if (next === lang) {
    return;
  }
  lang = next;
  try {
    localStorage.setItem("lang", next);
  } catch {}
  for (const listener of listeners) {
    listener();
  }
}

export function useLangStore() {
  const current = useSyncExternalStore(subscribe, currentLang, currentLang);
  return { lang: current, setLang };
}

