import { useEffect, useState } from "react";

export type Lang = "ru" | "en" | "uk" | "be" | "kk";

export const LANGUAGES: { code: Lang; country: string; native: string }[] = [
  { code: "ru", country: "ru", native: "Русский" },
  { code: "en", country: "gb", native: "English" },
  { code: "uk", country: "ua", native: "Українська" },
  { code: "be", country: "by", native: "Беларуская" },
  { code: "kk", country: "kz", native: "Қазақша" },
];

let lang: Lang = (localStorage.getItem("lang") as Lang | null) ?? "ru";
const listeners = new Set<() => void>();

export function useLangStore() {
  const [, force] = useState(0);
  useEffect(() => {
    const cb = () => force((x) => x + 1);
    listeners.add(cb);
    return () => {
      listeners.delete(cb);
    };
  }, []);
  return {
    lang,
    setLang: (l: Lang) => {
      lang = l;
      localStorage.setItem("lang", l);
      listeners.forEach((cb) => cb());
    },
  };
}

